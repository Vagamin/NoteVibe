import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:notevibe/main.dart';
import 'package:notevibe/ui/providers.dart';
import 'app_test.dart' show makeServices;

void main() {
  testWidgets('vertical scroll works while board swipe is settling', (tester) async {
    tester.view.physicalSize = const Size(412, 915);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    late AppServices s;
    await tester.runAsync(() async => s = await makeServices());
    final folder = s.store.createFolder('Работа');
    for (var i = 0; i < 30; i++) {
      s.store.createNote(title: 'Заметка $i', folderId: folder.id);
    }
    await tester.pumpWidget(ProviderScope(overrides: [servicesProvider.overrideWithValue(s)], child: const NoteVibeApp()));
    await tester.pumpAndSettle();
    await tester.fling(find.byType(PageView), const Offset(-260, 0), 1000);
    await tester.pump(const Duration(milliseconds: 16));
    await tester.dragFrom(const Offset(200, 450), const Offset(0, -280));
    await tester.pumpAndSettle();
    final vertical = tester.stateList<ScrollableState>(find.byType(Scrollable))
      .where((s) => s.widget.axisDirection == AxisDirection.down);
    expect(vertical.any((s) => s.position.pixels > 50), isTrue);
    final container = ProviderScope.containerOf(tester.element(find.byType(NoteVibeApp)));
    expect(container.read(folderSelectionProvider), folder.id);
    expect(tester.takeException(), isNull);
  });
  testWidgets('desktop title arrows cycle folders in both directions', (tester) async {
    tester.view.physicalSize = const Size(1280, 800);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    late AppServices s;
    await tester.runAsync(() async => s = await makeServices());
    final folder = s.store.createFolder('Работа');
    s.store.createNote(title: 'Заметка', folderId: folder.id);
    await tester.pumpWidget(ProviderScope(overrides: [servicesProvider.overrideWithValue(s)], child: const NoteVibeApp()));
    await tester.pumpAndSettle();
    final container = ProviderScope.containerOf(tester.element(find.byType(NoteVibeApp)));
    await tester.tap(find.byTooltip('Предыдущая папка (Alt+←)'));
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), folder.id);
    await tester.tap(find.byTooltip('Следующая папка (Alt+→)'));
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), isNull);
    expect(tester.takeException(), isNull);
  });
  testWidgets('mobile boards switch by swipe and tab without changing notes', (tester) async {
    tester.view.physicalSize = const Size(412, 915);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    late AppServices s;
    await tester.runAsync(() async => s = await makeServices());
    final folder = s.store.createFolder('Работа');
    s.store.createNote(title: 'Рабочая заметка', folderId: folder.id);
    await tester.pumpWidget(ProviderScope(overrides: [servicesProvider.overrideWithValue(s)], child: const NoteVibeApp()));
    await tester.pumpAndSettle();
    final container = ProviderScope.containerOf(tester.element(find.byType(NoteVibeApp)));
    await tester.drag(find.byType(PageView), const Offset(-350, 0));
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), folder.id);
    await tester.longPress(find.text('Работа'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('NoteVibe'));
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), isNull);
    expect(tester.widget<PageView>(find.byType(PageView)).controller!.page!.round() % 2, 0);
    await tester.drag(find.byType(PageView), const Offset(350, 0));
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), folder.id);
    expect(s.store.listNotes().single.folderId, folder.id);
    s.store.updateNote(folder.id, title: 'Переименованная');
    await tester.pumpAndSettle();
    expect(find.text('Переименованная'), findsOneWidget);
    final second = s.store.createFolder('Вторая');
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), folder.id);
    await tester.drag(find.byType(PageView), const Offset(-350, 0));
    await tester.pumpAndSettle();
    expect(container.read(folderSelectionProvider), second.id);
    expect(find.text('Вторая'), findsOneWidget);
    expect(tester.takeException(), isNull);
  });
  testWidgets('folder management and rename fit narrow screen', (tester) async {
    tester.view.physicalSize = const Size(320, 740);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    late AppServices s;
    await tester.runAsync(() async => s = await makeServices());
    final folder = s.store.createFolder('Очень длинное название папки для заметок');
    await tester.pumpWidget(ProviderScope(overrides: [servicesProvider.overrideWithValue(s)],
      child: const NoteVibeApp()));
    await tester.pumpAndSettle();
    final container = ProviderScope.containerOf(tester.element(find.byType(NoteVibeApp)));
    container.read(folderSelectionProvider.notifier).select(folder.id);
    await tester.pumpAndSettle();
    await tester.longPress(find.text(folder.title));
    await tester.pumpAndSettle();
    await tester.tap(find.byTooltip('Управление папкой'));
    await tester.pumpAndSettle();
    expect(tester.takeException(), isNull);
    await tester.tap(find.byTooltip('Назад к папкам'));
    await tester.pumpAndSettle();
    expect(find.text('Папки'), findsOneWidget);
    await tester.tap(find.byTooltip('Управление папкой'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Переименовать папку'));
    await tester.pumpAndSettle();
    expect(tester.takeException(), isNull);
    await tester.enterText(find.byType(TextField).last, 'Новое имя');
    await tester.tap(find.text('Сохранить'));
    await tester.pumpAndSettle();
    expect(s.store.listFolders().single.title, 'Новое имя');
    expect(find.text('Папки'), findsOneWidget);
    await tester.tap(find.byTooltip('Закрыть'));
    await tester.pumpAndSettle();
    expect(find.text('Новое имя'), findsOneWidget);
    expect(tester.takeException(), isNull);
  });
  testWidgets('folder filters notes, searches globally and moves selected notes', (tester) async {
    late AppServices s;
    await tester.runAsync(() async => s = await makeServices());
    final folder = s.store.createFolder('Учёба');
    final first = s.store.createNote(title: 'Лекция', folderId: folder.id);
    s.store.createNote(title: 'Покупки');
    await tester.pumpWidget(ProviderScope(overrides: [servicesProvider.overrideWithValue(s)], child: const NoteVibeApp()));
    await tester.pumpAndSettle();
    ref() => ProviderScope.containerOf(tester.element(find.byType(NoteVibeApp)));
    ref().read(folderSelectionProvider.notifier).select(folder.id);
    await tester.pumpAndSettle();
    expect(find.text('Лекция'), findsOneWidget);
    expect(find.text('Покупки'), findsNothing);
    ref().read(searchQueryProvider.notifier).set('Покупки');
    await tester.pumpAndSettle();
    expect(find.text('Покупки'), findsOneWidget);
    ref().read(searchQueryProvider.notifier).set('');
    ref().read(selectionProvider.notifier).toggle(first.id);
    await tester.pumpAndSettle();
    await tester.tap(find.text('Переместить (1)'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Без папки'));
    await tester.pumpAndSettle();
    expect(s.store.getNote(first.id)!.folderId, isNull);
    ref().read(folderSelectionProvider.notifier).select(folder.id);
    s.store.setSetting('folders_enabled', 'false');
    ref().invalidate(foldersEnabledProvider);
    await tester.pumpAndSettle();
    expect(find.text('Лекция'), findsOneWidget);
    expect(find.text('Покупки'), findsOneWidget);
    expect(find.text('Все заметки'), findsNothing);
    expect(s.store.listFolders().single.id, folder.id);
  });
}
